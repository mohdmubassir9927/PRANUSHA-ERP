-- PRANUSHA ERP - Secure starter database setup
-- Run this entire script once in Supabase > SQL Editor.
-- Staff can view and add records. Only Admin can edit or delete records.
-- This reuses the existing public.profiles table with columns: id, role.

create table if not exists public.site_transactions (
  id bigint generated by default as identity primary key,
  entry_date date not null default current_date,
  category text not null check (
    category in ('Site Expense', 'Purchase', 'Sales', 'Labour', 'Contractor', 'Other')
  ),
  description text not null,
  amount numeric(14,2) not null default 0 check (amount >= 0),
  party_name text,
  reference_no text,
  created_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.site_bills (
  id bigint generated by default as identity primary key,
  bill_type text not null check (bill_type in ('RA Bill', 'Final Bill')),
  bill_no text not null,
  bill_date date not null default current_date,
  client_name text,
  gross_amount numeric(14,2) not null default 0,
  gst_amount numeric(14,2) not null default 0,
  net_amount numeric(14,2) not null default 0,
  created_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now(),
  unique (bill_type, bill_no)
);

alter table public.site_transactions enable row level security;
alter table public.site_bills enable row level security;

-- Transactions: all signed-in users can view; users can add only as themselves.
drop policy if exists "erp_transactions_read" on public.site_transactions;
create policy "erp_transactions_read"
on public.site_transactions for select to authenticated
using (true);

drop policy if exists "erp_transactions_insert" on public.site_transactions;
create policy "erp_transactions_insert"
on public.site_transactions for insert to authenticated
with check (auth.uid() = created_by);

-- Only Admin can edit or delete transactions.
drop policy if exists "erp_transactions_update" on public.site_transactions;
create policy "erp_transactions_update"
on public.site_transactions for update to authenticated
using (
  exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  )
)
with check (
  exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  )
);

drop policy if exists "erp_transactions_delete_admin" on public.site_transactions;
create policy "erp_transactions_delete_admin"
on public.site_transactions for delete to authenticated
using (
  exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  )
);

